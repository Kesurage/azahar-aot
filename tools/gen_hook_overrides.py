#!/usr/bin/env python3
"""Make the C overrides that give a 3dsrecomp library the MH4U port's hook points.

  python3 tools/gen_hook_overrides.py [mh4u/config/hooks.txt] [overrides/mh4u/mh4u_hooks.c]
                                      [--thumb 0xADDR ...]

Each line of hooks.txt ("<address> <name>  # purpose") becomes one RECOMP_OVERRIDE. The override
hands the call to the host's hook (mh4u/port/src/hooks_aot.cpp, which runs port/src/hooks.cpp
unchanged) or, while no hook is set, runs the original function. Run this again, and rebuild the
library, whenever config/hooks.txt changes. All of MH4U's hook points are ARM functions
(config/functions.tsv); name any Thumb one with --thumb.
"""
import re
import sys

args = sys.argv[1:]
thumb = set()
while "--thumb" in args:
    i = args.index("--thumb")
    thumb.add(int(args[i + 1], 16))
    del args[i:i + 2]
src = args[0] if len(args) > 0 else "mh4u/config/hooks.txt"
out = args[1] if len(args) > 1 else "overrides/mh4u/mh4u_hooks.c"
tun_src = args[2] if len(args) > 2 else "mh4u/config/tunables.txt"

# config/tunables.txt: "<address> <original immediate> <name>  # why"; spots that share a name share
# one variable in the library
tunables = {}  # name -> (original, [addresses])
for line in open(tun_src):
    words = line.partition("#")[0].split()
    if len(words) < 3:
        continue
    address, original, name = int(words[0], 16), int(words[1], 0), words[2]
    entry = tunables.setdefault(name, (original, []))
    if entry[0] != original:
        sys.exit("%s: %s has two different original values" % (tun_src, name))
    entry[1].append(address)

hooks = []
for line in open(src):
    text, _, _ = line.partition("#")
    words = text.split()
    if not words:
        continue
    name = re.sub(r"\s+", " ", line.partition("#")[0].strip())
    hooks.append((int(words[0], 16), " ".join(words[1:2])))

C = r'''/* GENERATED by tools/gen_hook_overrides.py from mh4u/config/hooks.txt: do not edit by hand.

   The MH4U port's hook points (frame-rate cap, widescreen, touch overlay, screen filters,
   skip button, ...) for a library made by 3dsrecomp. Each override hands the call to the host's
   hook, mh4u/port/src/hooks_aot.cpp, which runs port/src/hooks.cpp; with no hook set it runs the
   original function. The registers and flags travel through an AotHookCall, so the host's code
   doesn't have to know this library's context. The layout must match hooks_aot.cpp's. */
#include "overrides.h"

#define AOT_HOOK_ABI 1

typedef struct AotHookCall AotHookCall;
struct AotHookCall {
    uint32_t abi, index;
    uint32_t r[16];
    uint32_t n, z, c, v;
    uint8_t *const *write_pages;
    Context *context;
    Code original;
    uint32_t ran;
    uint32_t reserved;
    void (*run_original)(AotHookCall *);
    void (*call_guest)(AotHookCall *, uint32_t target);
};
typedef void (*AotHookFn)(AotHookCall *);

/* set by the host (index = the hook's place in azahar_aot_hook_addrs); null runs the original */
RECOMP_EXPORT AotHookFn azahar_aot_hooks[@COUNT@];
RECOMP_EXPORT const uint32_t azahar_aot_hook_abi = AOT_HOOK_ABI;
RECOMP_EXPORT const uint32_t azahar_aot_hook_call_size = sizeof(AotHookCall);
RECOMP_EXPORT const uint32_t azahar_aot_hook_count = @COUNT@;
RECOMP_EXPORT const uint32_t azahar_aot_hook_addrs[@COUNT@] = {
@ADDRS@
};

static void aot_load(AotHookCall *hc, int with_pc) {
    Context *ctx = hc->context;
    for (int i = 0; i < 15; i++) ctx->r[i] = hc->r[i];
    if (with_pc) ctx->r[15] = hc->r[15];
    ctx->n = hc->n != 0; ctx->z = hc->z != 0; ctx->c = hc->c != 0; ctx->v = hc->v != 0;
}

static void aot_store(AotHookCall *hc, int with_pc) {
    Context *ctx = hc->context;
    for (int i = 0; i < 15; i++) hc->r[i] = ctx->r[i];
    if (with_pc) hc->r[15] = ctx->r[15];
    hc->n = ctx->n; hc->z = ctx->z; hc->c = ctx->c; hc->v = ctx->v;
}

/* the hook runs the function the override replaced */
static void aot_run_original(AotHookCall *hc) {
    Context *ctx = hc->context;
    aot_load(hc, 0);
    if (UNLIKELY(++ctx->depth > RECOMP_DEPTH_LIMIT)) {
        ctx->depth--;
        ctx->exit = EXIT_UNWIND;
    } else {
        hc->original(ctx);
        ctx->depth--;
    }
    aot_store(hc, 1); /* r15: where the function returned to */
    hc->ran = 1;
}

/* the hook calls a guest function (r14 is its return address) and gets the registers back */
static void aot_call_guest(AotHookCall *hc, uint32_t target) {
    Context *ctx = hc->context;
    const uint32_t pc = ctx->r[15];
    const uint8_t thumb = ctx->thumb;
    aot_load(hc, 0);
    ctx->r[15] = target & ~1u;
    ctx->thumb = target & 1;
    if (UNLIKELY(++ctx->depth > RECOMP_DEPTH_LIMIT)) {
        ctx->depth--;
        ctx->exit = EXIT_UNWIND;
    } else {
        recomp_call(ctx);
        ctx->depth--;
    }
    aot_store(hc, 0);
    ctx->r[15] = pc;
    ctx->thumb = thumb;
}

static void aot_dispatch(Context *ctx, uint32_t index, Code original) {
    AotHookFn hook = azahar_aot_hooks[index];
    if (!hook) {
        CALL(original);
        return;
    }
    AotHookCall hc;
    hc.abi = AOT_HOOK_ABI;
    hc.index = index;
    for (int i = 0; i < 15; i++) hc.r[i] = ctx->r[i];
    hc.r[15] = ctx->r[14]; /* a hook that skips the function returns to the caller */
    hc.n = ctx->n; hc.z = ctx->z; hc.c = ctx->c; hc.v = ctx->v;
    hc.write_pages = ctx->write_pages;
    hc.context = ctx;
    hc.original = original;
    hc.ran = 0;
    hc.reserved = 0;
    hc.run_original = aot_run_original;
    hc.call_guest = aot_call_guest;
    hook(&hc);
    aot_load(&hc, 0);
    if (hc.ran) {
        ctx->r[15] = hc.r[15];
        return;
    }
    RETURN_TO(hc.r[15]);
}

@OVERRIDES@

@TUNABLES@
'''
over = []
for i, (a, n) in enumerate(hooks):
    lit = "0x%08X" % (a | (1 if a in thumb else 0))
    over.append("RECOMP_OVERRIDE(%s) { aot_dispatch(ctx, %d, RECOMP_ORIGINAL(%s)); } /* %s */" % (lit, i, lit, n))
tun = []
if tunables:
    tun.append("/* Tunables: instructions whose immediate operand (a size the wide render changes, config/tunables.txt)")
    tun.append("   3dsrecomp generates as a read of the variable named here, so the host can change it while the game")
    tun.append("   runs and the function stays recompiled. The variable holds the original immediate until then. The")
    tun.append("   marks need a 3dsrecomp that knows RECOMP_TUNABLE (recomp/src/overrides.rs). */")
    tun.append("#define RECOMP_TUNABLE(address, symbol)")
    names = sorted(tunables)
    for name in names:
        tun.append("RECOMP_HIDDEN uint32_t azahar_tunable_%s = %d;" % (name, tunables[name][0]))
        for address in tunables[name][1]:
            tun.append("RECOMP_TUNABLE(0x%08X, azahar_tunable_%s)" % (address, name))
    tun.append("")
    tun.append("/* what the host sees: each tunable's name and where its variable is */")
    tun.append("RECOMP_EXPORT const uint32_t azahar_aot_tunable_count = %d;" % len(names))
    tun.append("RECOMP_EXPORT const char *const azahar_aot_tunable_names[%d] = { %s };" % (len(names), ", ".join('"%s"' % n for n in names)))
    tun.append("RECOMP_EXPORT uint32_t *const azahar_aot_tunable_vars[%d] = { %s };" % (len(names), ", ".join("&azahar_tunable_%s" % n for n in names)))
text = (C.replace("@COUNT@", str(len(hooks)))
         .replace("@ADDRS@", ",\n".join("    0x%08X" % (a | (1 if a in thumb else 0)) for a, _ in hooks))
         .replace("@OVERRIDES@", "\n".join(over))
         .replace("@TUNABLES@", "\n".join(tun)))
open(out, "w").write(text)
print("wrote %s: %d hook points, %d tunables" % (out, len(hooks), sum(len(v[1]) for v in tunables.values())))
